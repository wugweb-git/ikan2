#!/usr/bin/env python3
"""Regenerate .design-sync/asset-shims/ from src/assets/*.jpg.

The converter's bundle loader map has no .jpg entry and bundle.mjs must not be forked, so
tsconfig paths resolve '@/assets/<f>.jpg' to '<f>.jpg.ts' here. Run after changing any cover
image, or the previews keep rendering the old one."""
import base64, glob, os

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
os.makedirs(".design-sync/asset-shims", exist_ok=True)
for p in sorted(glob.glob("src/assets/*.jpg")):
    b64 = base64.b64encode(open(p, "rb").read()).decode()
    out = f".design-sync/asset-shims/{os.path.basename(p)}.ts"
    open(out, "w").write(
        "/* Generated by make-asset-shims.py - do not edit. */\n"
        f'export default "data:image/jpeg;base64,{b64}";\n')
    print(f"{os.path.getsize(out)/1024:8.0f} KB  {out}")
